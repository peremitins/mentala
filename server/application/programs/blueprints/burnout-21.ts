// Сад #4 «Выгорание» (burnout_21, комнатная азалия - Rhododendron simsii).
// Тема: восстановление при выгорании - усталость, отстранённость, ощущение
// «что бы я ни делал, всё без толку». Акцент универсальный: работа, быт,
// забота о близких, учёба.
// Методическая база: рамка выгорания Maslach (истощение, цинизм/отстранённость,
// падение веры в свою эффективность) как карта понимания; поведенческая
// активация (восстановительная активность, баланс нагрузки и отдыха); КПТ
// (работа с правилами «отдых - это лень», «надо всё успеть», перфекционизм,
// проверка прогнозов в поведенческом эксперименте); управление нагрузкой и
// границы дел; self-compassion (Neff) против внутреннего гонщика; ACT
// (ценности под усталостью). Без обещаний «силы вернутся» и без диагнозов.
// Красная линия: выгорание ≠ депрессия - в саде есть шаг с честной
// маршрутизацией к живой помощи.
// Опора на предыдущие сады: регуляция нервной системы (calm_anxiety_30),
// доброта к себе (self_kindness_21), границы и просьба о поддержке
// (relationships_21).
