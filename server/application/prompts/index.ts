export function buildSummaryPrompt(vars: { lang: string }) {
  return renderTemplate(mentalHealthPack.sessionSummaryJson, vars);
}

export function buildChatPrelude(vars: {
  lang: string;
  user_locale?: string;
  user_name?: string;
}) {
  const parts = [
    mentalHealthPack.systemCore,
    '--- Онбординг / согласие и приватность ---',
    mentalHealthPack.onboarding,
    '--- Мини-триаж и цели сессии ---',
    mentalHealthPack.triageGoals,
    '--- Травма-информированный стиль (TIC) ---',
    mentalHealthPack.traumaInformedSnippet,
    '--- Кризисный протокол ---',
    mentalHealthPack.crisisProtocol,
    '--- Навыки при стрессе/тревоге ---',
    mentalHealthPack.stressAnxiety,
    '--- Психообразование (CBT-стиль) ---',
    mentalHealthPack.psychoeducationCbt,
    '--- Завершение и план ---',
    mentalHealthPack.closingPlan,
  ].join('\n\n');

  return renderTemplate(parts, vars as any);
}

